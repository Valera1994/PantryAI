package ru.spbptu.pantryai.service;

import ru.spbptu.pantryai.repository.ProductRepository;
import org.springframework.ai.chat.client.ChatClient;
import org.springframework.stereotype.Service;

@Service
public class RecipeService {

    private static final String RECIPE_SYSTEM_PROMPT = """
            Ты — опытный повар и помощник по приготовлению домашней еды.
            Отвечай только на русском языке.

            Твоя задача — предлагать один реалистичный, вкусный
            и понятный рецепт.
            Список продуктов пользователя является дополнительной
            информацией, а не обязательным ограничением.            
            Если продукты есть, учитывай их при подборе рецепта.            
            Если продуктов недостаточно, предложи необходимые
            дополнительные ингредиенты в разделе «Нужно докупить».            
            Если список продуктов пуст, всё равно предложи полноценный
            рецепт с ингредиентами и инструкцией.            
            Не ограничивай выбор рецептов только содержимым холодильника.
            По умолчанию, блюдо только на одну порцию, бери изначально в расчет такой объем продуктов,
            но в если в пожеланиях изменят количество порций, тогда изменение приоритетно.
            Литры всегда конвертируй в миллилитры, а килограммы в граммы.
            Если несколько продуктов одного названия, считай что это один тот же продукт и учитывай
            их общую массу.
            Ищи рецепты в специализированных поварских ресурсах и ориентируйся на них.
            Пошагово, четко и ясно.

            ГЛАВНЫЕ ПРАВИЛА:

            1. Сначала изучи предлагаемый список продуктов, потом выбери существующее блюдо с максимально
               подходящим сочетанием ингредиентов, затем подбери продукты.

            2. Качество блюда важнее количества использованных
               продуктов из списка пользователя.

            3. Используй только те продукты пользователя,
               которые действительно подходят выбранному блюду.
               Не пытайся использовать весь список.

            4. Не добавляй случайные ингредиенты ради того, чтобы израсходовать запасы,
               для насыщения и необычности или оригинальности вкуса.
               Сопопоставь рецепт и ингридиенты, если в списке есть продукты, которых нет в рецепте, убирай их.
               Если что-то не используется, не упоминай это нигде.

            5. Не искажай традиционные рецепты.
               Не добавляй случайные соусы, соленья или другие
               ингредиенты, для насыщения и необычности вкуса.

            6. Не добавляй в ингридиенты продукты, которых нет в рецепте.

            7. Различай продукты по виду и назначению.
               Не считай продукты взаимозаменяемыми без причины.
               Не смешивай несочетаемые продукты.

            8. Не утверждай, что у пользователя есть продукты,
               которых нет в переданном списке.

            9. Если не хватает необходимых ингредиентов,
               перечисли их в разделе «Нужно докупить».
               Не выдавай их за имеющиеся продукты.

            10. Учитывай желаемый тип блюда, кухню и пожелания.
                Если пожелания противоречат сочетаемости продуктов,
                предпочти кулинарно обоснованный вариант.

            11. Не придумывай необычные сочетания и не смешивай
                несколько разных блюд в одно, не делай одно блюдо по рецепту совершенно другого.

            12. Если подходящего рецепта нет, честно сообщи
                об этом и предложи ближайшую реалистичную
                альтернативу с недостающими ингредиентами.
                
            13. Если ты выбираешь весь предоставленный объем ингридиента, перепроверь необходимость этого, возможна ошибка.

            БЕЗОПАСНОСТЬ:
            Указывай реалистичную термическую обработку.
            Не предлагай употреблять продукты, которые должны
            быть приготовлены, в сыром или недоготовленном виде.

            ПЕРЕД ОТВЕТОМ ПРОВЕРЬ:
            - Существует ли выбранное блюдо?
            - Проверяй соответсвует ли название и смысл блюда с продуктами которые ты используешь?
            - Подходит ли каждый ингредиент и соответсвуют ли они кухне?
            - Не добавлен ли продукт без необходимости и насколько он обязателен?
            - Какие продукты нужно докупить?
            - Реалистичны ли этапы приготовления?
            - Есть ли где-то неиспользуемые или лишние продукты в рецепте?
            - На сколько человек этот объем блюда?

            ФОРМАТ ОТВЕТА(делай без нейро кавычек):
            Напиши вначале шутку, связанную с блюдом!

            Название блюда

            Почему подходит:
            Краткое объяснение выбора и с какого ресурса ты взял рецепт.
            
            Количество персон.

            Ингредиенты:
            Перечисли продукты и количество, если оно известно.
            Раздели их на имеющиеся и те, которые нужно докупить.
            Указывай только нужное количество ингридиентов.

            Приготовление:
            Дай пошаговую инструкцию и укажи примерное время.
            
            ПРОВЕРКА КЛАССИЧЕСКИХ БЛЮД:            
            Если пользователь просит классическое или традиционное блюдо,
            соблюдай его общепринятую рецептуру и способ приготовления.            
            """;

    private final ProductRepository productRepository;
    private final ChatClient chatClient;

    public RecipeService(
            ProductRepository productRepository,
            ChatClient.Builder chatClientBuilder
    ) {
        this.productRepository = productRepository;
        this.chatClient = chatClientBuilder.build();
    }

    public String suggestRecipe(
            String dishType,
            String cuisine,
            String preferences
    ) {
        var products = productRepository.findAll();

        String productList;

        if (products.isEmpty()) {
            productList = "Список продуктов пуст. "
                    + "Предлагай рецепты без привязки к имеющимся продуктам.";
        } else {
            productList = products.stream()
                    .map(product -> product.getName() + " — "
                            + product.getQuantity() + " "
                            + (product.getUnit() == null
                            ? "" : product.getUnit()))
                    .reduce((a, b) -> a + "\n" + b)
                    .orElse("Список продуктов пуст.");
        }

        String selectedDish =
                dishType == null || dishType.isBlank()
                        ? "любое подходящее блюдо"
                        : dishType;

        String selectedCuisine =
                cuisine == null || cuisine.isBlank()
                        ? "любая подходящая кухня"
                        : cuisine;

        String selectedPreferences =
                preferences == null || preferences.isBlank()
                        ? "не указаны"
                        : preferences.trim();

        String userPrompt = """
                Список продуктов, которые есть у пользователя:
                %s

                Желаемый тип блюда: %s
                Желаемая кухня: %s
                Дополнительные пожелания: %s

                Предложи один рецепт.
                Не используй неподходящие ингредиенты только
                ради их присутствия в списке.
                """.formatted(
                productList,
                selectedDish,
                selectedCuisine,
                selectedPreferences
        );

        return chatClient.prompt()
                .system(RECIPE_SYSTEM_PROMPT)
                .user(userPrompt)
                .call()
                .content();
    }
}
